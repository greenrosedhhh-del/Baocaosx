-- 2. Bảng ca làm việc PX ĐÚC 2 (duc2_shifts)
CREATE TABLE IF NOT EXISTS duc2_shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_date TEXT NOT NULL,
    shift_num INT NOT NULL,
    status TEXT NOT NULL DEFAULT 'in_progress',
    doc_code TEXT DEFAULT '',
    doc_number TEXT DEFAULT '',
    shift_leader TEXT NOT NULL,
    leader_signature TEXT,
    safety_production INT DEFAULT 1,
    safety_ppe INT DEFAULT 1,
    safety_equip INT DEFAULT 1,
    staff_total INT DEFAULT 16,
    staff_present INT DEFAULT 16,
    leave_permitted_names TEXT DEFAULT '',
    leave_unpermitted_names TEXT DEFAULT 'KO',
    stopper_start INT DEFAULT 0,
    stopper_added INT DEFAULT 0,
    stopper_used INT DEFAULT 0,
    stopper_remaining INT DEFAULT 0,
    nozzle_start INT DEFAULT 0,
    nozzle_added INT DEFAULT 0,
    nozzle_used INT DEFAULT 0,
    nozzle_remaining INT DEFAULT 0,
    default_product TEXT DEFAULT 'Bi 40',
    default_customer TEXT DEFAULT 'Molycop',
    default_steel_grade TEXT DEFAULT 'Cr18-19.5',
    issues TEXT DEFAULT '',
    suggestions TEXT DEFAULT '',
    start_time TEXT DEFAULT '',
    end_time TEXT DEFAULT '',
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    submitted_at TIMESTAMPTZ,
    UNIQUE(report_date, shift_num)
);

-- 3. Bảng Khuôn tạo hình (duc2_molding_items)
CREATE TABLE IF NOT EXISTS duc2_molding_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT NOT NULL REFERENCES duc2_shifts(id) ON DELETE CASCADE,
    sort_order INT DEFAULT 0,
    product_name TEXT DEFAULT '',
    customer TEXT DEFAULT '',
    start_time TEXT DEFAULT '',
    end_time TEXT DEFAULT '',
    time_range TEXT DEFAULT '',
    counter_start BIGINT,
    counter_end BIGINT,
    molds_created INT,
    molds_poured INT,
    notes TEXT DEFAULT ''
);

-- 4. Bảng Lò rót đáy - nhập trực tiếp từng lù (duc2_pouring_batches)
CREATE TABLE IF NOT EXISTS duc2_pouring_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT NOT NULL REFERENCES duc2_shifts(id) ON DELETE CASCADE,
    batch_no INT NOT NULL,
    product_name TEXT DEFAULT '',
    customer TEXT DEFAULT '',
    temp_max INT,
    temp_min INT,
    start_time TEXT DEFAULT '',
    end_time TEXT DEFAULT '',
    furnace_code TEXT DEFAULT '',
    heat_no INT,
    furnace_heat_label TEXT DEFAULT '',
    status TEXT NOT NULL DEFAULT 'done',
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Bảng Lò nấu (duc2_melting_furnaces)
CREATE TABLE IF NOT EXISTS duc2_melting_furnaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT NOT NULL REFERENCES duc2_shifts(id) ON DELETE CASCADE,
    sort_order INT DEFAULT 0,
    product_name TEXT DEFAULT '',
    customer TEXT DEFAULT '',
    steel_grade TEXT DEFAULT '',
    furnace_code TEXT NOT NULL,
    heat_count INT DEFAULT 0,
    prev_lining_life INT DEFAULT 0,
    lining_life INT DEFAULT 0,
    manual_heat_override INT DEFAULT 0,
    manual_life_override INT DEFAULT 0,
    notes TEXT DEFAULT ''
);

