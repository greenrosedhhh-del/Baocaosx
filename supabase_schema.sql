-- 1. Bảng ca làm việc (shifts)
CREATE TABLE IF NOT EXISTS shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_date TEXT NOT NULL,
    shift_num INT NOT NULL,
    shift_leader TEXT NOT NULL,
    safety_production INT DEFAULT 1,
    safety_ppe INT DEFAULT 1,
    safety_equip INT DEFAULT 1,
    staff_total INT DEFAULT 5,
    staff_present INT DEFAULT 5,
    leave_permitted INT DEFAULT 0,
    leave_permitted_names TEXT,
    leave_rotating INT DEFAULT 0,
    leave_rotating_names TEXT,
    leave_unpermitted INT DEFAULT 0,
    leave_unpermitted_names TEXT,
    issues TEXT,
    suggestions TEXT,
    start_time TEXT,
    end_time TEXT,
    shift_tasks TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,
    UNIQUE(report_date, shift_num)
);

-- 2. Bảng chi tiết đóng gói (packaging_items)
CREATE TABLE IF NOT EXISTS packaging_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT REFERENCES shifts(id) ON DELETE CASCADE,
    product_name TEXT,
    customer TEXT,
    from_val TEXT,
    to_val TEXT,
    weight_sorted NUMERIC,
    weight_waste NUMERIC,
    notes TEXT
);

-- 3. Bảng chi tiết giỏ bi (basket_items)
CREATE TABLE IF NOT EXISTS basket_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT REFERENCES shifts(id) ON DELETE CASCADE,
    product_name TEXT,
    customer TEXT,
    from_val TEXT,
    to_val TEXT,
    steel_grade TEXT,
    basket_count NUMERIC,
    total_weight NUMERIC,
    notes TEXT
);

-- 4. Bảng chi tiết bi xóc (tumbling_items)
CREATE TABLE IF NOT EXISTS tumbling_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id BIGINT REFERENCES shifts(id) ON DELETE CASCADE,
    product_name TEXT,
    customer TEXT,
    m1 NUMERIC,
    m2 NUMERIC,
    total_weight NUMERIC,
    notes TEXT
);

-- 5. Bảng cấu hình danh mục (presets)
CREATE TABLE IF NOT EXISTS presets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL,
    name TEXT NOT NULL,
    sort_order INT DEFAULT 0,
    active INT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(category, name)
);

-- 6. Bảng tài khoản (users)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL,
    active INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    must_change_password INT NOT NULL DEFAULT 0,
    session_version INT NOT NULL DEFAULT 0,
    workshop TEXT NOT NULL DEFAULT 'nllt',
    signature_data TEXT
);

